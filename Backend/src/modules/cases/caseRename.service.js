// Renames a case (the internal team's "edit name" on the case page): single, family, an employer matter (the company) and an employer's employee.
//
// The new name must be the only name anywhere the case is shown or used - lists, the Pipeline, emails, notifications, the profile that fills USCIS forms - so it is
// written to every place the OLD name is held, and to nowhere else:
//   1. the case: clientName, petitionerName, participants, employee identity / pending slot, invites and the questionnaire answers;
//   2. the canonical profile, ONLY through CanonicalProfileService.applyStaffEdit (the one sanctioned writer: versioned, audited, survives every rebuild). Its version
//      bump also flags every filled form as out of date, so the forms are regenerated by the app's own stale-form flow - stored form data is never edited here;
//   3. the linked client / beneficiary records and the linked LOGIN accounts whose name is exactly the old name (so emails that greet the account use the new name);
//   4. for an employer matter, its employees' copies of the company name (questionnaire answers, profile);
//   5. GoHighLevel: employee cards and an individual case's card are renamed by the existing background job (the stored card name is left for that job to update).
// History (timelines, audit trails, canonical history, e-mails already sent) is never rewritten. Every write is a compare-and-set on the exact values read, so a
// concurrent edit is never overwritten (the rename retries once, then asks the team to try again). Safe to repeat: matching is by the old name.
const mongoose = require("mongoose");
const Case = require("../../models/Case");
const User = require("../../models/User");
const logger = require("../../utils/logger");
const core = require("./caseRename.core");

const STAFF_ROLES = new Set(["super_admin", "admin", "team_lead", "case_manager"]);
const EXCLUDE_HEAVY = "-canonicalHistory -timeline -auditHistory";
const MAX_CANONICAL_EDITS = 300;

const httpError = (status, message, code) => Object.assign(new Error(message), { status, code });
const isEmployerMatter = (caseData) => caseData?.caseRole === "principal" && caseData?.caseStructure === "employer_employee";
/**
 * What kind of name the case holds, which decides what the team is asked for:
 *   "company" - an employer matter: the company name
 *   "name"    - an RFE / NOIR / NOID / MTR case: ONE name (it is not known whether the filer is a person or a company, so it is never split)
 *   "person"  - single, family and employee cases: first name, optional middle name, optional last name
 */
function nameKind(caseData) {
  if (isEmployerMatter(caseData)) return "company";
  const { hasCustomChecklist } = require("../../config/visaCategories");
  const visaType = String(caseData?.visaType || caseData?.petitionType || "").trim().toUpperCase();
  if (visaType && hasCustomChecklist(visaType)) return "name";
  return "person";
}
const currentName = (caseData) => core.clean(caseData?.clientName) || core.clean(caseData?.employeeIdentity?.name) || core.clean(caseData?.pendingEmployee?.name);

/** The parts of a case that hold its name (everything except the canonical profile, which has its own writer). */
const nameScope = (caseData) => ({
  clientName: caseData.clientName,
  petitionerName: caseData.petitionerName,
  participants: caseData.participants,
  employeeIdentity: caseData.employeeIdentity,
  pendingEmployee: caseData.pendingEmployee,
  employeeInvite: caseData.employeeInvite,
  beneficiaryInvite: caseData.beneficiaryInvite,
  questionnaireData: caseData.questionnaireData,
});

/**
 * Compare-and-set of leaf changes on one document: the filter requires every leaf to STILL hold the value that was read, so a concurrent edit is never overwritten.
 * Returns { applied, skipped } - skipped = changes whose path cannot be addressed (a key with a "." in it).
 */
async function applyLeafChanges(Model, id, changes, { set = {}, addToSet = null } = {}) {
  const usable = changes.filter((change) => change.safe);
  const skipped = changes.length - usable.length;
  if (!usable.length && !Object.keys(set).length && !addToSet) return { applied: true, skipped };
  const filter = { _id: id };
  const update = { $set: { ...set } };
  for (const change of usable) {
    filter[change.path] = change.from === undefined ? { $exists: false } : change.from;
    update.$set[change.path] = change.to;
  }
  if (addToSet) update.$addToSet = addToSet;
  const result = await Model.updateOne(filter, update);
  return { applied: (result.matchedCount ?? result.n ?? 0) > 0, skipped };
}

/** Reads a document, computes its changes and applies them; retries once when a concurrent edit got in between. */
async function applyWithRetry({ Model, id, read, compute, extra }) {
  let lastSkipped = 0;
  for (let attempt = 0; attempt < 2; attempt += 1) {
    const doc = await read();
    if (!doc) return { applied: true, count: 0, skipped: 0 };
    const changes = compute(doc);
    if (!changes.length && !extra) return { applied: true, count: 0, skipped: 0 };
    const outcome = await applyLeafChanges(Model, id, changes, extra ? extra(doc) : {});
    lastSkipped = outcome.skipped;
    if (outcome.applied) return { applied: true, count: changes.length - outcome.skipped, skipped: outcome.skipped };
  }
  return { applied: false, count: 0, skipped: lastSkipped };
}

async function renameLinkedUsers(caseData, oldName, newName) {
  const { invalidateUserCache } = require("../../config/redis");
  const ids = [...new Set([caseData.user, caseData.petitionerUser, caseData.beneficiaryUser, caseData.employerUser].filter(Boolean).map(String))];
  let renamed = 0;
  for (const id of ids) {
    try {
      const account = await User.findById(id).select("name displayName").lean();
      if (!account) continue;
      const set = {};
      const filter = { _id: account._id };
      // only an account that carries exactly the old name: an employer-filled employee slot shares the employer's login, and that name is not this person's
      if (core.fold(account.name) === core.fold(oldName)) { set.name = newName; filter.name = account.name; }
      if (core.fold(account.displayName) === core.fold(oldName)) { set.displayName = newName; filter.displayName = account.displayName; }
      if (!Object.keys(set).length) continue;
      const result = await User.updateOne(filter, { $set: set });
      if ((result.matchedCount ?? result.n ?? 0) > 0) { renamed += 1; await invalidateUserCache(account._id); }
    } catch (error) {
      logger.warn("case_rename_user_failed", { caseId: String(caseData._id), userId: id, error: error.message });
    }
  }
  return renamed;
}

async function renameLinkedRecords(caseData, opts) {
  let renamed = 0;
  const records = [
    [require("../../models/Client"), caseData.clientProfile],
    [require("../../models/Beneficiary"), caseData.beneficiary],
  ];
  for (const [Model, id] of records) {
    if (!id) continue;
    try {
      const outcome = await applyWithRetry({
        Model,
        id,
        read: () => Model.findById(id).select("firstName middleName lastName fullName").lean(),
        compute: (doc) => core.replaceNames({ firstName: doc.firstName, middleName: doc.middleName, lastName: doc.lastName, fullName: doc.fullName }, opts).changes,
      });
      if (outcome.count) renamed += 1;
    } catch (error) {
      logger.warn("case_rename_record_failed", { caseId: String(caseData._id), error: error.message });
    }
  }
  return renamed;
}

/** An employer matter: the employees carry copies of the company name (their questionnaire answers and profile). Best effort per employee. */
async function renameEmployees(principal, opts, actor, req, dryRun) {
  const CanonicalProfileService = require("../canonical/services/CanonicalProfileService");
  const caseService = require("./case.service");
  const children = await Case.find({ parentCase: principal._id }).select("_id").lean();
  const result = { employees: children.length, updated: 0 };
  for (const { _id } of children) {
    try {
      const read = () => Case.findById(_id).select(EXCLUDE_HEAVY).lean();
      const child = await read();
      if (!child) continue;
      const canonicalChanges = child.canonicalProfile?.profile ? core.replaceNames(child.canonicalProfile.profile, opts).changes.filter((change) => change.safe).slice(0, MAX_CANONICAL_EDITS) : [];
      if (dryRun) { result.updated += canonicalChanges.length || core.replaceNames({ participants: child.participants, questionnaireData: child.questionnaireData }, opts).changes.length ? 1 : 0; continue; }
      if (canonicalChanges.length && caseService.canAccessCase(actor, child)) {
        await CanonicalProfileService.applyStaffEdit(_id, canonicalChanges.map((change) => ({ path: change.path, value: change.to, reason: "case_renamed" })), actor, req);
      }
      const outcome = await applyWithRetry({
        Model: Case,
        id: _id,
        read,
        compute: (doc) => core.replaceNames({ participants: doc.participants, questionnaireData: doc.questionnaireData }, opts).changes,
      });
      if (canonicalChanges.length || outcome.count) result.updated += 1;
    } catch (error) {
      logger.warn("case_rename_employee_failed", { caseId: String(principal._id), childId: String(_id), error: error.message });
    }
  }
  return result;
}

/** After the response: GoHighLevel hears about the new name through its existing background jobs. Never throws. */
function notifyGhl(caseData, childIds) {
  try {
    const hooks = require("../../integrations/ghl/ghlOutboundHooks");
    if (caseData.caseRole === "employee") hooks.employeeChanged(caseData._id);
    childIds.forEach((childId) => hooks.employeeChanged(childId));
    const ghl = caseData.integrations?.ghl;
    if (ghl?.opportunityId && ghl.role === "individual" && caseData.caseRole !== "employee") {
      const env = require("../../config/env");
      if (env.ghl?.enabled && env.ghl?.token) {
        setImmediate(async () => {
          try {
            const aux = require("../../integrations/ghl/ghlAuxOutbound");
            const job = await aux.queueJob(caseData._id, "rename");
            if (job) require("../../integrations/ghl/ghlOutboundService").processJobSoon(job._id);
          } catch (error) {
            logger.warn("case_rename_ghl_queue_failed", { caseId: String(caseData._id), error: error.message });
          }
        });
      }
    }
  } catch (error) {
    logger.warn("case_rename_ghl_notify_failed", { caseId: String(caseData?._id), error: error.message });
  }
}

/**
 * The Client portal, Admin and the Attorney portal listen for "something on this case changed" and re-read through their own authorized API, so a rename shows
 * on screens that are open right now without a refresh. ("employees" is the scope the Attorney portal re-reads on.) Never throws, never carries the name itself.
 */
function notifyOpenSessions(caseId, childIds, actor) {
  try {
    require("../realtime/caseLiveUpdates").notifyCaseDataChanged([caseId, ...childIds], ["name", "answers", "employees"], { actor, reason: "case_renamed" });
  } catch (error) {
    logger.warn("case_rename_live_signal_failed", { caseId: String(caseId), error: error.message });
  }
}

/**
 * input: { name } for an employer matter (the company) or an RFE / NOIR / NOID / MTR case (one name), { firstName, middleName?, lastName? } for a person.
 * dryRun: only reports what would change.
 */
async function renameCase({ caseId, input, actor, req, dryRun = false }) {
  if (!mongoose.isValidObjectId(caseId)) throw httpError(400, "Invalid case id");
  if (!STAFF_ROLES.has(String(actor?.role || ""))) throw httpError(403, "Not authorized to rename this case");
  const caseService = require("./case.service");
  const first = await Case.findById(caseId).select(EXCLUDE_HEAVY).lean();
  if (!first) throw httpError(404, "Case not found");
  if (!caseService.canAccessCase(actor, first)) throw httpError(403, "Not authorized to rename this case");

  const kind = nameKind(first);
  const oldName = currentName(first);
  if (!oldName) throw httpError(400, "This case has no name yet.", "CASE_HAS_NO_NAME");
  const checked = core.validateNameInput(input, { kind });
  if (checked.error) throw httpError(400, checked.error, "INVALID_NAME");
  const opts = { oldName, newName: checked.name, parts: checked.parts };

  // 1. the canonical profile (the only writer: versioned, audited, durable). Done first: it can refuse (a concurrent edit) before anything else was changed.
  const canonicalChanges = first.canonicalProfile?.profile ? core.replaceNames(first.canonicalProfile.profile, opts).changes.filter((change) => change.safe).slice(0, MAX_CANONICAL_EDITS) : [];
  const caseChanges = core.replaceNames(nameScope(first), opts).changes;
  if (dryRun) {
    return { success: true, dryRun: true, kind, previousName: oldName, name: checked.name, wouldChange: { profile: canonicalChanges.length, case: caseChanges.filter((change) => change.safe).length, skipped: caseChanges.filter((change) => !change.safe).length } };
  }
  if (!canonicalChanges.length && !caseChanges.length && core.fold(oldName) === core.fold(checked.name)) {
    return { success: true, unchanged: true, kind, name: oldName };
  }
  if (canonicalChanges.length) {
    const CanonicalProfileService = require("../canonical/services/CanonicalProfileService");
    await CanonicalProfileService.applyStaffEdit(caseId, canonicalChanges.map((change) => ({ path: change.path, value: change.to, reason: "case_renamed" })), actor, req);
  }

  // 2. the case itself (compare-and-set, one retry), plus the marker that stops a stale GoHighLevel name from coming back
  const now = new Date();
  const outcome = await applyWithRetry({
    Model: Case,
    id: first._id,
    read: () => Case.findById(first._id).select(EXCLUDE_HEAVY).lean(),
    compute: (doc) => core.replaceNames(nameScope(doc), opts).changes,
    extra: () => ({
      set: { "nameEdit.at": now, "nameEdit.by": actor._id, "nameEdit.previousName": oldName },
      addToSet: { "nameEdit.previousNames": oldName },
    }),
  });
  if (!outcome.applied) throw httpError(409, "The case was just updated by someone else. Please try again.", "CONCURRENT_EDIT");

  // 3. linked accounts / records, and an employer's employees (each guarded and best effort: the case itself is already renamed)
  const linked = await Case.findById(first._id).select("user petitionerUser beneficiaryUser employerUser clientProfile beneficiary").lean();
  const usersRenamed = await renameLinkedUsers(linked || first, oldName, checked.name);
  const recordsRenamed = await renameLinkedRecords(linked || first, opts);
  let employees = { employees: 0, updated: 0 };
  let childIds = [];
  if (kind === "company") {
    employees = await renameEmployees(first, opts, actor, req, false);
    childIds = (await Case.find({ parentCase: first._id }).select("_id").lean()).map((child) => child._id);
  }

  // 4. the trail: a timeline entry and an audit record (best effort, never changes the answer)
  try {
    const full = await Case.findById(first._id);
    if (full) {
      caseService.addTimelineEvent(full, "case", "Case name changed", `The name was changed from "${oldName}" to "${checked.name}"`, actor, { source: "case_rename", previousName: oldName, name: checked.name });
      await full.save();
    }
    await caseService.writeAuditLog("case_renamed", first, actor, { from: oldName, to: checked.name }, req);
  } catch (error) {
    logger.warn("case_rename_trail_failed", { caseId: String(first._id), error: error.message });
  }

  notifyGhl(first, childIds);
  notifyOpenSessions(first._id, childIds, actor);
  return {
    success: true,
    kind,
    previousName: oldName,
    name: checked.name,
    updated: { case: outcome.count, profile: canonicalChanges.length, accounts: usersRenamed, records: recordsRenamed, employees: employees.updated },
    skippedUnaddressable: outcome.skipped,
  };
}

/** What the edit form needs: the kind of name (a company or a person), the current name and, for a person, their real first / middle / last name. */
async function getEditInfo({ caseId, actor }) {
  if (!mongoose.isValidObjectId(caseId)) throw httpError(400, "Invalid case id");
  if (!STAFF_ROLES.has(String(actor?.role || ""))) throw httpError(403, "Not authorized to rename this case");
  const caseService = require("./case.service");
  const doc = await Case.findById(caseId).select(EXCLUDE_HEAVY).lean();
  if (!doc) throw httpError(404, "Case not found");
  if (!caseService.canAccessCase(actor, doc)) throw httpError(403, "Not authorized to rename this case");
  const kind = nameKind(doc);
  const name = currentName(doc);
  if (kind !== "person") return { success: true, kind, name, parts: null };
  const parts = core.findNameParts([doc.canonicalProfile?.profile, doc.questionnaireData, doc.employeeIdentity, doc.pendingEmployee], name) || core.splitName(name);
  return { success: true, kind, name, parts };
}

module.exports = { renameCase, getEditInfo, isEmployerMatter, nameKind, currentName };
